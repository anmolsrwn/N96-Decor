#!/usr/bin/env node
/* =========================================================
   N96 DECOR: build static project and city pages
   ---------------------------------------------------------
   Run after you change projects or cities in js/data.js:

       node tools/build-pages.js

   What it does (no packages needed, just Node.js):
   - writes  work/<id>.html    for every project in N96.projects
   - writes  cities/<id>.html  for every city in N96.cities
   - writes  js/generated-pages.js  (the list of pages above)
   - removes generated pages for projects or cities you have since
     deleted (and the old project-*.html / city-*.html layout)

   Each page has its own title, description and link-preview
   (Open Graph) tags, plus the real text and photos in the HTML,
   so Google, WhatsApp and Instagram can read it without running
   JavaScript. The site's JavaScript still redraws the page
   from js/data.js, so the page always looks right.

   Templates: project.html and city.html (edit those for layout).
   Titles used here must match js/main.js (search "keep in sync").
   ========================================================= */
"use strict";
var fs = require("fs");
var path = require("path");
var vm = require("vm");

var ROOT = path.resolve(__dirname, "..");
var MARK = "<!-- GENERATED by tools/build-pages.js. Do not edit; edit js/data.js or the template and run the build again. -->";

/* ---------- load js/data.js ---------- */
function loadData() {
  var sandbox = {};
  sandbox.window = sandbox;
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, "js", "data.js"), "utf8"), sandbox, { filename: "data.js" });
  if (!sandbox.N96 || !sandbox.N96.projects || !sandbox.N96.cities) throw new Error("js/data.js did not define N96.projects and N96.cities");
  return sandbox.N96;
}
var N96 = loadData();
var SITE = String(process.env.SITE_URL || (N96.config && N96.config.siteUrl) || "").replace(/\/+$/, "");

/* ---------- helpers (same behaviour as js/main.js) ---------- */
function esc(s) {
  return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
    return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
  });
}
function shortDate(d) {
  var parts = String(d).split(" ");
  return parts.length === 2 ? parts[0].slice(0, 3) + " " + parts[1] : d;
}
function catLabel(id) {
  var c = N96.categories.filter(function (x) { return x.id === id; })[0];
  return c ? c.label : id;
}
function projectById(id) { return N96.projects.filter(function (p) { return p.id === id; })[0]; }
function projectFile(p) { return "work/" + p.id + ".html"; }
function cityFile(c) { return "cities/" + c.id + ".html"; }
function photoPath(p, n) { return "images/projects/" + p.id + "/" + n + ".jpg"; }
function exists(rel) { return fs.existsSync(path.join(ROOT, rel)); }
// only photos that really exist on disk (the live JavaScript hides missing ones too)
function photos(p) {
  var out = [];
  for (var i = 1; i <= p.photos; i++) if (exists(photoPath(p, i))) out.push(photoPath(p, i));
  return out;
}
function cityProjects(c) { return N96.projects.filter(function (p) { return p.city === c.id; }); }
function trim(text, max) {
  text = String(text || "").replace(/\s+/g, " ").trim();
  if (text.length <= max) return text;
  var cut = text.slice(0, max - 1), sp = cut.lastIndexOf(" ");
  return (sp > max * 0.6 ? cut.slice(0, sp) : cut).replace(/[ ,;:.\-]+$/, "") + "\u2026";
}
function abs(rel) { return SITE ? SITE + "/" + rel : ""; }

/* Replace one exact piece of the template; fail loudly if the template changed. */
function swap(html, from, to, label) {
  if (html.indexOf(from) < 0) throw new Error("Template is missing: " + label + "\n  expected: " + from);
  return html.replace(from, function () { return to; });
}
function readTemplate(name) {
  var html = fs.readFileSync(path.join(ROOT, name), "utf8");
  if (html.indexOf(MARK) > -1) throw new Error(name + " is a generated file, not a template");
  return html;
}

/* ---------- shared pieces ---------- */
var NAV_LINKS = [["index.html", "Home"], ["founders.html", "About / Founders"], ["services.html", "Services"], ["projects.html", "Projects"],
  ["gallery.html", "Gallery"], ["stories.html", "Couple Stories"], ["join.html", "Join Us"], ["index.html#contact", "Contact"]];
// shown only when JavaScript is off; the site's JavaScript replaces the header and footer
function plainNav(label) {
  return "<noscript><nav aria-label=\"" + label + "\">" + NAV_LINKS.map(function (l) { return "<a href=\"" + l[0] + "\">" + l[1] + "</a>"; }).join(" | ") + "</nav></noscript>";
}

function headTags(o) {
  var t = [];
  t.push("<meta name=\"description\" content=\"" + esc(o.description) + "\">");
  if (o.noindex) t.push("<meta name=\"robots\" content=\"noindex\">");
  if (SITE) t.push("<link rel=\"canonical\" href=\"" + esc(abs(o.file)) + "\">");
  t.push("<meta property=\"og:site_name\" content=\"" + esc((N96.config && N96.config.name) || "N96 Decor") + "\">");
  t.push("<meta property=\"og:type\" content=\"website\">");
  t.push("<meta property=\"og:title\" content=\"" + esc(o.ogTitle) + "\">");
  t.push("<meta property=\"og:description\" content=\"" + esc(o.description) + "\">");
  if (SITE) t.push("<meta property=\"og:url\" content=\"" + esc(abs(o.file)) + "\">");
  if (SITE && o.image) {
    t.push("<meta property=\"og:image\" content=\"" + esc(abs(o.image)) + "\">");
    t.push("<meta name=\"twitter:card\" content=\"summary_large_image\">");
  }
  return t.join("\n  ");
}

function projectCard(p) {
  var cover = photoPath(p, 1);
  return "<a class=\"project-card\" href=\"" + projectFile(p) + "\" data-cat=\"" + esc(p.category) + "\">" +
    "<div class=\"img\"><span class=\"tag\">" + esc(p.event) + "</span>" + (p.sample ? "<span class=\"sample\">Sample</span>" : "") +
    (exists(cover) ? "<img src=\"" + cover + "\" alt=\"" + esc(p.title + ", " + p.venue) + "\" loading=\"lazy\">" : "") + "</div>" +
    "<div><h3>" + esc(p.title) + "</h3>" +
    "<div class=\"meta\"><span>" + esc(p.venue) + ", " + esc(p.location) + "</span><span>" + esc(shortDate(p.date)) + "</span></div></div></a>";
}

/* ---------- project page ---------- */
function projectPage(template, p) {
  var list = photos(p);
  var title = p.title + " \u00b7 " + p.venue + ", " + p.location + " | N96 Decor";   // keep in sync with js/main.js
  var desc = trim(p.lead, 158);

  var facts = [
    ["Event", p.event], ["Venue", p.venue], ["Location", p.location], ["Date", p.date],
    ["Guests", p.guests ? p.guests + "+" : ""],
    [p.styledFor ? "Styled for" : "Category", p.styledFor || catLabel(p.category)]
  ].filter(function (f) { return f[1]; });

  var hero = (list[0] ? "<img src=\"" + list[0] + "\" alt=\"" + esc(p.title) + "\">" : "") +
    "<div class=\"crumbs\"><div class=\"wrap\"><a href=\"index.html\">Home</a> &nbsp;/&nbsp; <a href=\"projects.html\">Projects</a> &nbsp;/&nbsp; " + esc(p.title) + "</div></div>";

  var types = N96.categories.map(function (c) {
    var n = c.id === "all" ? N96.projects.length : N96.projects.filter(function (x) { return x.category === c.id; }).length;
    return "<a class=\"chip" + (c.id === p.category ? " is-active" : "") + "\" href=\"projects.html" + (c.id === "all" ? "" : "#" + c.id) + "\">" + esc(c.label) + "<span class=\"count\">" + n + "</span></a>";
  }).join("");

  var i = N96.projects.indexOf(p), n = N96.projects.length;
  var prev = N96.projects[(i - 1 + n) % n], next = N96.projects[(i + 1) % n];
  var main =
    "<div class=\"detail-title\"><span class=\"eyebrow\">" + esc(p.event) + " \u00b7 " + esc(p.venue) + "</span>" +
      "<h1>" + esc(p.tagline) + "</h1><p class=\"sub\">" + esc(p.subtitle) + "</p></div>" +
    "<dl class=\"facts\">" + facts.map(function (f) { return "<div class=\"fact\"><dt>" + esc(f[0]) + "</dt><dd>" + esc(f[1]) + "</dd></div>"; }).join("") + "</dl>" +
    "<div class=\"detail-story\"><p class=\"lead\">" + esc(p.lead) + "</p>" + (p.story || []).map(function (t) { return "<p>" + esc(t) + "</p>"; }).join("") +
      (p.highlights ? "<ul class=\"highlights\">" + p.highlights.map(function (h) { return "<li>" + esc(h) + "</li>"; }).join("") + "</ul>" : "") + "</div>" +
    "<div class=\"photo-grid\">" + list.map(function (src, k) {
      return "<button type=\"button\" data-i=\"" + k + "\" aria-label=\"Open photo " + (k + 1) + "\"><img src=\"" + src + "\" alt=\"" + esc(p.title) + " photo " + (k + 1) + "\" loading=\"lazy\"></button>";
    }).join("") + "</div>" +
    "<div class=\"prev-next\"><a href=\"" + projectFile(prev) + "\"><small>\u2190 Previous</small>" + esc(prev.title) + "</a>" +
      "<a href=\"" + projectFile(next) + "\" style=\"text-align:right\"><small>Next \u2192</small>" + esc(next.title) + "</a></div>";

  var more = "<span class=\"eyebrow\">Keep exploring</span><h3>More Projects</h3><div class=\"more-list\">" +
    N96.projects.filter(function (x) { return x.id !== p.id; }).map(function (o) {
      var c = photoPath(o, 1);
      return "<a class=\"more-item\" href=\"" + projectFile(o) + "\">" + (exists(c) ? "<img src=\"" + c + "\" alt=\"\" loading=\"lazy\">" : "") +
        "<div><strong>" + esc(o.title) + "</strong><span>" + esc(o.venue) + " \u00b7 " + esc(shortDate(o.date)) + (o.sample ? " \u00b7 Sample" : "") + "</span></div></a>";
    }).join("") + "</div><p style=\"margin-top:20px\"><a class=\"btn btn--ghost\" href=\"projects.html\">All projects</a></p>";

  var html = template;
  html = swap(html, "<title>Project | N96 Decor</title>", "<title>" + esc(title) + "</title>", "<title>");
  html = swap(html, "<meta name=\"description\" content=\"Project details, venue, date and photos from an N96 Decor celebration.\">",
    headTags({ description: desc, ogTitle: title, file: projectFile(p), image: list[0], noindex: !!p.sample }), "meta description");
  html = swap(html, "<body data-page=\"project\">", "<body data-page=\"project\" data-id=\"" + esc(p.id) + "\">", "<body>");
  html = swap(html, "<header id=\"site-header\"></header>", "<header id=\"site-header\">" + plainNav("Main") + "</header>", "header");
  html = swap(html, "<section class=\"detail-hero\" id=\"detail-hero\"></section>", "<section class=\"detail-hero\" id=\"detail-hero\">" + hero + "</section>", "detail-hero");
  html = swap(html, "id=\"detail-types\" aria-label=\"Browse projects by type\"></div>", "id=\"detail-types\" aria-label=\"Browse projects by type\">" + types + "</div>", "detail-types");
  html = swap(html, "<article id=\"detail-main\"></article>", "<article id=\"detail-main\">" + main + "</article>", "detail-main");
  html = swap(html, "<aside class=\"more-aside\" id=\"detail-more\" aria-label=\"More projects\"></aside>", "<aside class=\"more-aside\" id=\"detail-more\" aria-label=\"More projects\">" + more + "</aside>", "detail-more");
  html = swap(html, "<footer id=\"site-footer\"></footer>", "<footer id=\"site-footer\">" + plainNav("Footer") + "</footer>", "footer");
  return stamp(html);
}

/* ---------- city page ---------- */
function cityPage(template, c) {
  var list = cityProjects(c);
  var title = "Celebrations designed in " + c.name + " | N96 Decor";   // keep in sync with js/main.js
  var desc = list.length
    ? "Weddings and celebrations designed by N96 Decor in " + c.name + " (" + c.region + "): " + list.map(function (p) { return p.title; }).join(", ") + "."
    : "N96 Decor designs weddings and celebrations in " + c.name + " (" + c.region + "). Projects from here are coming soon.";
  var firstImage = null;
  list.forEach(function (p) { if (!firstImage && exists(photoPath(p, 1))) firstImage = photoPath(p, 1); });

  var banner = "<img class=\"mark\" src=\"images/brand/logo-mark.png\" alt=\"\">" +
    "<span class=\"eyebrow\">Venues we've worked at</span><h1>" + esc(c.name) + "</h1>" +
    "<p>" + esc(c.region) + " \u00b7 " + (list.length ? list.length + (list.length === 1 ? " project" : " projects") : "Projects coming soon") + "</p>";
  var cards = list.length ? list.map(projectCard).join("") :
    "<div class=\"empty-note\">We have designed celebrations in " + esc(c.name) + " and will add them here soon. Planning something in " + esc(c.name) + "? <a href=\"index.html#contact\">Get in touch</a>.</div>";
  var others = N96.cities.map(function (x) {
    return "<a class=\"chip" + (x.id === c.id ? " is-active" : "") + "\" href=\"" + cityFile(x) + "\">" + esc(x.name) + "<span class=\"count\">" + cityProjects(x).length + "</span></a>";
  }).join("");

  var html = template;
  html = swap(html, "<title>Venues | N96 Decor</title>", "<title>" + esc(title) + "</title>", "<title>");
  html = swap(html, "<meta name=\"description\" content=\"Weddings and celebrations designed by N96 Decor in this city.\">",
    headTags({ description: desc, ogTitle: title, file: cityFile(c), image: firstImage, noindex: !list.length }), "meta description");
  html = swap(html, "<body data-page=\"city\">", "<body data-page=\"city\" data-id=\"" + esc(c.id) + "\">", "<body>");
  html = swap(html, "<header id=\"site-header\"></header>", "<header id=\"site-header\">" + plainNav("Main") + "</header>", "header");
  html = swap(html, "<div class=\"wrap\" id=\"city-banner\"></div>", "<div class=\"wrap\" id=\"city-banner\">" + banner + "</div>", "city-banner");
  html = swap(html, "id=\"city-others\" aria-label=\"Other cities\"></div>", "id=\"city-others\" aria-label=\"Other cities\">" + others + "</div>", "city-others");
  html = swap(html, "<div class=\"project-grid project-grid--4\" id=\"city-projects\"></div>", "<div class=\"project-grid project-grid--4\" id=\"city-projects\">" + cards + "</div>", "city-projects");
  html = swap(html, "<footer id=\"site-footer\"></footer>", "<footer id=\"site-footer\">" + plainNav("Footer") + "</footer>", "footer");
  return stamp(html);
}

// These pages live one folder down (work/, cities/). <base href="../"> keeps every link and file path
// (css/, js/, images/, index.html ...) working exactly as on the pages in the main folder.
function stamp(html) {
  html = html.replace(/^(<!DOCTYPE html>\r?\n)/i, function (m) { return m + MARK + "\n"; });
  return swap(html, "<meta charset=\"UTF-8\">", "<meta charset=\"UTF-8\">\n  <base href=\"../\">", "<meta charset>");
}

/* ---------- write everything ---------- */
function main() {
  var ids = {};
  N96.projects.forEach(function (p) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(p.id)) throw new Error("Project id \"" + p.id + "\" must use only lowercase letters, numbers and dashes");
    if (ids[p.id]) throw new Error("Two projects share the id \"" + p.id + "\"");
    ids[p.id] = true;
  });
  N96.cities.forEach(function (c) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(c.id)) throw new Error("City id \"" + c.id + "\" must use only lowercase letters, numbers and dashes");
  });

  var projectTpl = readTemplate("project.html"), cityTpl = readTemplate("city.html");
  var written = {};
  ["work", "cities"].forEach(function (d) { fs.mkdirSync(path.join(ROOT, d), { recursive: true }); });
  N96.projects.forEach(function (p) {
    fs.writeFileSync(path.join(ROOT, projectFile(p)), projectPage(projectTpl, p));
    written[projectFile(p)] = true;
  });
  N96.cities.forEach(function (c) {
    fs.writeFileSync(path.join(ROOT, cityFile(c)), cityPage(cityTpl, c));
    written[cityFile(c)] = true;
  });

  // remove generated pages for projects or cities that no longer exist (never touches hand-written files)
  var removed = [];
  function sweep(dir, pattern) {
    var folder = path.join(ROOT, dir);
    if (!fs.existsSync(folder)) return;
    fs.readdirSync(folder).forEach(function (f) {
      var rel = dir ? dir + "/" + f : f;
      if (!pattern.test(f) || written[rel]) return;
      if (fs.readFileSync(path.join(folder, f), "utf8").indexOf(MARK) < 0) return;
      fs.unlinkSync(path.join(folder, f)); removed.push(rel);
    });
  }
  sweep("work", /\.html$/); sweep("cities", /\.html$/);
  sweep("", /^(project|city)-.+\.html$/);   // pages from the first version, which sat in the main folder

  fs.writeFileSync(path.join(ROOT, "js", "generated-pages.js"),
    "/* AUTO-GENERATED by tools/build-pages.js. Do not edit. */\n" +
    "window.N96_PAGES = " + JSON.stringify({
      projects: N96.projects.map(function (p) { return p.id; }),
      cities: N96.cities.map(function (c) { return c.id; })
    }, null, 2) + ";\n");

  console.log("Built " + N96.projects.length + " project pages and " + N96.cities.length + " city pages." + (removed.length ? " Removed: " + removed.join(", ") + "." : ""));
  if (!SITE) console.log("Note: siteUrl is empty in js/data.js, so canonical and link-preview image/url tags were skipped. Set it once you know your web address, then run this again.");
}

main();
